package net.datamancy.platform

import kotlin.test.*

class JellyfinRuntimeTest {
    private val image = "example.org/jellyfin@sha256:" + "a".repeat(64)
    private val inventory = AcquiredInventory(1, "candidate", listOf(AcquiredImage("jellyfin", "upstream",
        "example.org/jellyfin:1", image, "b".repeat(64), emptyList(), image.substringAfter('@'), "amd64", "linux")))

    @Test fun `native media provider owns generated bytes homes and no host library`(): Unit {
        val source = JellyfinRuntime.spec(inventory)
        assertEquals(setOf("config", "cache", "media"), source.volumes.map { it.id }.toSet())
        assertTrue(source.processes.all { it.capabilities.isEmpty() && it.userId == 1000 && it.apparmorProfile == "p0v3-private-v1" })
        val init = source.processes.single { it.oneShot }.command.last()
        assertContains(init, "private-tone.wav")
        assertContains(init, "test ! -e /config/config/system.xml")
        assertFalse("/mnt/media" in init)
        assertFails { JellyfinRuntime.spec(inventory.copy(images = emptyList())) }
    }

    @Test fun `canonical media projects original Jellyfin database cache and tone without replaying ffmpeg`(): Unit {
        val source = JellyfinRuntime.canonicalFragment(inventory, "q-111111111111-jellyfin")
        val inputs = JellyfinRuntime.canonicalInputs()
        assertEquals(PrivateDeployment.inputNames(source.spec).toSet(), inputs.keys)
        assertEquals(setOf("media-data", "media-web"), source.spec.networks.toSet())
        assertEquals(setOf("media-web"), source.webNetworks)
        val cold = JellyfinRuntime.coldRestoreFragment(source)
        assertEquals(source.spec.volumes, cold.spec.volumes)
        assertEquals(listOf("jellyfin"), cold.spec.processes.map { it.id })
        assertTrue(cold.spec.processes.single().dependencies.isEmpty())
        assertEquals(source.spec.processes.single { it.id == "jellyfin" }.volumes, cold.spec.processes.single().volumes)
        assertFails { JellyfinRuntime.coldRestoreFragment(source.copy(spec = source.spec.copy(
            volumes = source.spec.volumes.dropLast(1)))) }
    }
}
