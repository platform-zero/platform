package net.datamancy.platform

import java.nio.file.Files
import java.nio.file.Path
import java.nio.file.attribute.PosixFilePermissions
import java.util.Comparator
import java.util.concurrent.CountDownLatch
import java.util.concurrent.Executors
import java.util.concurrent.TimeUnit
import java.util.concurrent.atomic.AtomicBoolean
import kotlin.test.*

/** Host-filesystem unit regressions; never starts native services or publishes a release. */
class RuntimePreparationTest {
    private val name = "q-111111111111-unit"
    private val image = "example.org/app@sha256:" + "a".repeat(64)
    private val spec = PrivateDeploymentSpec(name = name, store = RuntimeStore.CANONICAL_V2, volumes = emptyList(),
        processes = listOf(RuntimeProcess("app", image, "b".repeat(64), 1000,
            entrypoint = "/usr/bin/app", files = listOf(RuntimeFile("app.conf", "/run/secrets/app.conf")),
            readiness = listOf("/usr/bin/true"))))

    private fun fixture(test: (Path) -> Unit) {
        val base = Files.createTempDirectory("native-preparation-",
            PosixFilePermissions.asFileAttribute(PosixFilePermissions.fromString("rwx------")))
        try { test(base) }
        finally { Files.walk(base).use { paths -> paths.sorted(Comparator.reverseOrder()).forEach(Files::delete) } }
    }

    @Test fun `unfinished lock-only namespace cannot mint new credentials`(): Unit = fixture { base ->
        RecoveryDeadline.within(60_000) {
            PrivateDeployment.withOrderedNativeLocks(listOf(name), base) { Unit }
        }
        val called = AtomicBoolean(false)
        assertFails { RuntimePreparation.prepare(spec, base) {
            called.set(true); mapOf("app.conf" to "untrusted new credentials")
        } }
        assertFalse(called.get())
        assertFalse(Files.exists(base.resolve("$name.json")))
    }

    @Test fun `preparation holds namespace gate through input and manifest fsync before no-target census`(): Unit =
        fixture { base ->
            val generating = CountDownLatch(1)
            val continueGeneration = CountDownLatch(1)
            val attemptedProbe = CountDownLatch(1)
            val workers = Executors.newFixedThreadPool(2)
            try {
                val prepared = workers.submit<Path> {
                    RuntimePreparation.prepare(spec, base) {
                        generating.countDown()
                        require(continueGeneration.await(5, TimeUnit.SECONDS))
                        mapOf("app.conf" to "original bytes only")
                    }
                }
                assertTrue(generating.await(5, TimeUnit.SECONDS))
                val probe = workers.submit<Boolean> {
                    attemptedProbe.countDown()
                    RecoveryDeadline.within(60_000) {
                        PrivateDeployment.withOrderedNativeLocks(listOf(name), base) {
                            Files.exists(base.resolve("$name.json")) &&
                                ReleaseLocks.privateBytes(base.resolve(name).resolve("app.conf"))
                                    .decodeToString() == "original bytes only"
                        }
                    }
                }
                assertTrue(attemptedProbe.await(5, TimeUnit.SECONDS))
                continueGeneration.countDown()
                assertEquals(base.resolve("$name.json"), prepared.get(5, TimeUnit.SECONDS))
                assertTrue(probe.get(5, TimeUnit.SECONDS), "No-target census cannot see an unfinished prepared root")
                assertEquals(base.resolve("$name.json"), RuntimePreparation.prepare(spec, base) {
                    error("An existing manifest must not regenerate inputs")
                })
            } finally {
                continueGeneration.countDown()
                workers.shutdownNow()
            }
        }

    @Test fun `no-target namespace wins before preparation and stays nonreusable`(): Unit = fixture { base ->
        val acquiredProbe = CountDownLatch(1)
        val releaseProbe = CountDownLatch(1)
        val workers = Executors.newFixedThreadPool(2)
        val generated = AtomicBoolean(false)
        try {
            val probe = workers.submit<Unit> {
                RecoveryDeadline.within(60_000) {
                    PrivateDeployment.withOrderedNativeLocks(listOf(name), base) {
                        acquiredProbe.countDown()
                        require(releaseProbe.await(5, TimeUnit.SECONDS))
                    }
                }
            }
            assertTrue(acquiredProbe.await(5, TimeUnit.SECONDS))
            val prepared = workers.submit<Boolean> {
                runCatching { RuntimePreparation.prepare(spec, base) {
                    generated.set(true); mapOf("app.conf" to "illegitimate regenerated bytes")
                } }.isFailure
            }
            releaseProbe.countDown()
            probe.get(5, TimeUnit.SECONDS)
            assertTrue(prepared.get(5, TimeUnit.SECONDS))
            assertFalse(generated.get())
            assertFalse(Files.exists(base.resolve("$name.json")))
        } finally {
            releaseProbe.countDown()
            workers.shutdownNow()
        }
    }
}
